CREATE TABLE public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    expense_date DATE NOT NULL,
    category VARCHAR(20) NOT NULL CHECK (category IN ('FUEL', 'SALARY', 'MAINTENANCE', 'UTILITIES', 'OTHER')),
    description VARCHAR(255) NOT NULL CHECK (btrim(description) <> ''),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    paid_to VARCHAR(255),
    notes VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'RECORDED' CHECK (status IN ('RECORDED', 'VOIDED')),
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    void_reason VARCHAR(500),
    voided_by VARCHAR(255),
    voided_at TIMESTAMPTZ,
    CHECK (category <> 'SALARY' OR (paid_to IS NOT NULL AND btrim(paid_to) <> '')),
    CHECK ((status = 'RECORDED' AND void_reason IS NULL AND voided_by IS NULL AND voided_at IS NULL)
        OR (status = 'VOIDED' AND void_reason IS NOT NULL AND btrim(void_reason) <> ''
            AND voided_by IS NOT NULL AND voided_at IS NOT NULL))
);

CREATE INDEX idx_expenses_date ON public.expenses (expense_date DESC, id DESC);
CREATE INDEX idx_expenses_category_date ON public.expenses (category, expense_date DESC, id DESC);

-- Expenses are accessed only through the authenticated Spring/JDBC API.
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;
DO $$
DECLARE api_role text;
BEGIN
    FOR api_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated')
    LOOP
        EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.expenses FROM %I', api_role);
    END LOOP;
END $$;
